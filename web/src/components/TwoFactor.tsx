import { useEffect, useState } from 'react';
import QRCode from 'qrcode';
import { api } from '../api';
import { buttonClass, inputClass, Notice } from './AuthCard';

type Step =
  | { name: 'loading' }
  | { name: 'off' }
  | { name: 'scan'; secret: string; uri: string; svg: string }
  | { name: 'codes'; codes: string[] }
  | { name: 'on'; left: number }
  | { name: 'change'; left: number; action: 'disable' | 'codes' };

/**
 * Turn the authenticator-app second factor on or off, and manage its recovery codes
 * (SECURITY.md M-12). The server holds the rules; this only collects what it asks for.
 *
 * The QR code is drawn here, as inline SVG, so the secret goes nowhere else — not to a
 * QR service, and not through an image URL the CSP (`img-src 'self'`) would block.
 */
export default function TwoFactor() {
  const [step, setStep] = useState<Step>({ name: 'loading' });
  const [password, setPassword] = useState('');
  const [code, setCode] = useState('');
  const [error, setError] = useState('');
  const [saved, setSaved] = useState(false);

  const refresh = async () => {
    const status = await api.auth.totp.status();
    setStep(status.enabled ? { name: 'on', left: status.recovery_codes_left } : { name: 'off' });
  };

  useEffect(() => {
    refresh().catch(() => setStep({ name: 'off' }));
  }, []);

  const reset = () => { setPassword(''); setCode(''); setError(''); setSaved(false); };
  const fail = (err: unknown, fallback: string) => setError(err instanceof Error ? err.message : fallback);

  const start = async (e: React.FormEvent) => {
    e.preventDefault();
    setError('');
    try {
      const { secret, otpauth_uri } = await api.auth.totp.setup(password);
      const svg = await QRCode.toString(otpauth_uri, { type: 'svg', margin: 1, width: 192 });
      setPassword('');
      setStep({ name: 'scan', secret, uri: otpauth_uri, svg });
    } catch (err) {
      fail(err, 'Could not start setup');
    }
  };

  const confirm = async (e: React.FormEvent) => {
    e.preventDefault();
    setError('');
    try {
      const { recovery_codes } = await api.auth.totp.enable(code);
      reset();
      setStep({ name: 'codes', codes: recovery_codes });
    } catch (err) {
      fail(err, 'That code was not accepted');
    }
  };

  const change = async (e: React.FormEvent, current: Extract<Step, { name: 'change' }>) => {
    e.preventDefault();
    setError('');
    try {
      if (current.action === 'disable') {
        await api.auth.totp.disable(password, code);
        reset();
        setStep({ name: 'off' });
      } else {
        const { recovery_codes } = await api.auth.totp.newRecoveryCodes(password, code);
        reset();
        setStep({ name: 'codes', codes: recovery_codes });
      }
    } catch (err) {
      fail(err, 'Could not change it');
    }
  };

  const card = 'bg-white border border-gray-200 rounded-xl p-5 mt-6';

  if (step.name === 'loading') return null;

  if (step.name === 'off') {
    return (
      <form onSubmit={start} className={card}>
        <h2 className="font-medium text-gray-900 mb-1">Two-factor sign-in</h2>
        <p className="text-sm text-gray-500 mb-4">
          Off. With it on, signing in also needs a code from an authenticator app on your phone, so
          a stolen password alone is not enough.
        </p>
        <input type="password" placeholder="Your password" autoComplete="current-password"
          value={password} onChange={e => setPassword(e.target.value)} className={inputClass} />
        {error && <Notice kind="error">{error}</Notice>}
        <button type="submit" className={buttonClass}>Set up</button>
      </form>
    );
  }

  if (step.name === 'scan') {
    return (
      <form onSubmit={confirm} className={card}>
        <h2 className="font-medium text-gray-900 mb-1">Scan with your authenticator app</h2>
        <p className="text-sm text-gray-500 mb-3">
          Use any authenticator app. If you cannot scan, enter this key by hand, then type the 6-digit
          code it shows.
        </p>
        {/* Generated by the qrcode library from the URI above, not from user input. */}
        <div className="mb-3 inline-block bg-white" dangerouslySetInnerHTML={{ __html: step.svg }} />
        <p className="text-sm font-mono break-all mb-4 select-all">{step.secret}</p>
        <input type="text" inputMode="numeric" placeholder="6-digit code" autoComplete="one-time-code"
          autoFocus value={code} onChange={e => setCode(e.target.value)} className={inputClass} />
        {error && <Notice kind="error">{error}</Notice>}
        <button type="submit" className={buttonClass}>Turn on</button>
        <button type="button" className="mt-2 text-sm text-gray-500 underline"
          onClick={() => { reset(); refresh(); }}>Cancel</button>
      </form>
    );
  }

  if (step.name === 'codes') {
    const text = step.codes.join('\n');
    return (
      <div className={card}>
        <h2 className="font-medium text-gray-900 mb-1">Save your recovery codes</h2>
        <p className="text-sm text-gray-500 mb-3">
          Each works once if you lose your phone. They are shown only now. Other devices signed in to
          this account have been signed out.
        </p>
        <pre className="bg-gray-50 border border-gray-200 rounded-lg p-3 text-sm font-mono select-all mb-3">{text}</pre>
        <button type="button" className="text-sm text-blue-600 underline mr-4"
          onClick={() => navigator.clipboard?.writeText(text)}>Copy</button>
        <label className="flex items-center gap-2 text-sm mt-3 mb-3">
          <input type="checkbox" checked={saved} onChange={e => setSaved(e.target.checked)} />
          I have saved them somewhere safe
        </label>
        <button type="button" className={buttonClass} disabled={!saved}
          onClick={() => { reset(); refresh(); }}>Done</button>
      </div>
    );
  }

  if (step.name === 'on') {
    return (
      <div className={card}>
        <h2 className="font-medium text-gray-900 mb-1">Two-factor sign-in</h2>
        <p className="text-sm text-gray-500 mb-4">
          On. {step.left} recovery code{step.left === 1 ? '' : 's'} left.
          {step.left <= 2 && ' Consider making new ones.'}
        </p>
        <button type="button" className="text-sm text-blue-600 underline mr-4"
          onClick={() => { reset(); setStep({ name: 'change', left: step.left, action: 'codes' }); }}>
          New recovery codes
        </button>
        <button type="button" className="text-sm text-red-600 underline"
          onClick={() => { reset(); setStep({ name: 'change', left: step.left, action: 'disable' }); }}>
          Turn off
        </button>
      </div>
    );
  }

  // Changing it takes the password and a current code, so a stolen session cannot do it.
  return (
    <form onSubmit={e => change(e, step)} className={card}>
      <h2 className="font-medium text-gray-900 mb-1">
        {step.action === 'disable' ? 'Turn off two-factor' : 'New recovery codes'}
      </h2>
      <p className="text-sm text-gray-500 mb-4">
        Enter your password and a current code from your app (or an unused recovery code).
      </p>
      <input type="password" placeholder="Your password" autoComplete="current-password"
        value={password} onChange={e => setPassword(e.target.value)} className={inputClass} />
      <input type="text" placeholder="Code" autoComplete="one-time-code" spellCheck={false}
        value={code} onChange={e => setCode(e.target.value)} className={inputClass} />
      {error && <Notice kind="error">{error}</Notice>}
      <button type="submit" className={buttonClass}>
        {step.action === 'disable' ? 'Turn off' : 'Make new codes'}
      </button>
      <button type="button" className="mt-2 text-sm text-gray-500 underline"
        onClick={() => { reset(); setStep({ name: 'on', left: step.left }); }}>Cancel</button>
    </form>
  );
}
